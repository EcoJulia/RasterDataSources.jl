# Markdown table of layers by source: ✓ where the source uses the layer name, or the name it uses.
function _era5_layer_table()
    sources = (
        ("`{Google,ARCO}`", keys(ERA5_LAYERS), ERA5_GOOGLE_NAMES),
        ("`{ECMWF,CDS}`", keys(ERA5_LAYERS), ERA5_CDS_NAMES),
        ("`{ECMWF,ARCO}`", _group_layers(ECMWF_ERA5_GROUPS), (;)),
        ("`{ECMWF,CDS,Land}`", keys(ERA5_LAND_LAYERS), ERA5_LAND_CDS_NAMES),
        ("`{ECMWF,ARCO,Land}`", _group_layers(ECMWF_ERA5_LAND_GROUPS), (;)),
    )
    function cell(layer, (_, layers, names))
        layer in layers || return ""
        name = get(names, layer, string(layer))
        name == string(layer) ? "✓" : "`$name`"
    end
    short(layer) = get(ERA5_LAYERS, layer, get(ERA5_LAND_LAYERS, layer, ""))
    header = "| Layer | Short name | " * join(first.(sources), " | ") * " |\n|" * repeat(" :--- |", 2 + length(sources))
    rows = map(sort!(union(keys(ERA5_LAYERS), keys(ERA5_LAND_LAYERS)))) do layer
        "| `:$layer` | `$(short(layer))` | " * join((cell(layer, s) for s in sources), " | ") * " |"
    end
    join([header; rows], "\n")
end
